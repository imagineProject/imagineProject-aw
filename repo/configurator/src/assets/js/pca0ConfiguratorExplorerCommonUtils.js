/**
 * Removes the UIDs of selected objects from session storage.
 * @param {string} sessionKey - The key to remove the UIDs from in session storage.
 * @param {Array} objects - Array of objects to extract UIDs from or an array of UIDs.
 */
export let removeUidsFromSessionStorage = ( sessionKey, objects ) => {
    if ( !objects ) {
        return;
    }
    // Return if the sessionstorage does not exist
    let storedUids = JSON.parse( sessionStorage.getItem( sessionKey ) );
    if ( !storedUids ) {
        return;
    }
    // Filter out the deleted uids
    const deletedUids = pca0CommonUtils.getUidsFromObjects( objects );
    storedUids = storedUids.filter( uid => !deletedUids.includes( uid ) );

    if ( storedUids.length > 0 ) {
        sessionStorage.setItem( sessionKey, JSON.stringify( storedUids ) );
    } else {
        sessionStorage.removeItem( sessionKey );
    }
};

/**
 * Build incremental list of features using request.listLoadInput
 * Note: this is not an actual (not supported) pagination for the list
 * [The code is using propertyWidgets-List example from SWF Storybook for aw-widget component
 * use StoryBook example to debug for any regressions in the future]
 * @param {Array} featureFacetValues - list of features objects as Facets, coming from SOA
 * @param {String} filter - applied string filter
 * @param {Object} listLoadInput - request.listLoadInput, native for aw-widget component
 * @returns {Object} info container to populate incremental list on DataProvider for Aw-Widget
 */
export let getIncrementalFeaturesList = ( featureFacetValues, filter, listLoadInput ) => {
    let objectValue = {};

    // Array may not be populated yet if user opens the dropdown before SOA processing is complete
    if( _.isUndefined( featureFacetValues ) ) {
        return {
            featuresIncrementalList: [],
            totalFound: 0,
            moreValuesExist: false
        };
    }

    // Filter/Update the entire list before scanning for matches
    if( !_.isNil( filter ) ) {
        featureFacetValues = featureFacetValues.filter( feature =>
            feature.propDisplayValue.toLowerCase().includes( filter.toLowerCase() ) );
    }

    let startIndex = listLoadInput.startChildNdx;
    let endIndex = startIndex + listLoadInput.pageSize;

    let lovEntries = [];
    for( let idx = startIndex; idx < endIndex; idx++ ) {
        if( featureFacetValues[ idx ] ) {
            lovEntries.push( featureFacetValues[ idx ] );
        }
    }

    objectValue.featuresIncrementalList = lovEntries;
    objectValue.totalFound = featureFacetValues.length;
    objectValue.moreValuesExist = endIndex < featureFacetValues.length;
    return objectValue;
};

