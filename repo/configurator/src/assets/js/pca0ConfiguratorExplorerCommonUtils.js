/**
 * Adjusts the selection of the tree based on the deletion operation's result.
 * In case of a successful deletion, the selection is set to the top context.
 * If there are errors, the selection is set to the objects that were not deleted.
 * @param {Object} eventData - eventData
 * @param {Object} treeDataProvider - Tree data provider
 * @returns {Boolean} true if context has objects under it, false otherwise
 */
export let setSelectedRowAfterNodesDeletion = ( eventData, treeDataProvider ) => {
    const { ServiceData: { partialErrors, deleted }, selectedObjects } = eventData;
    const selectedObjectsArr = pca0CommonUtils.convertToArray( selectedObjects );
    const viewModelCollection = treeDataProvider.getViewModelCollection();
    const treeNodes = viewModelCollection.getLoadedViewModelObjects();
    let shouldGridVisible = true;

    if( partialErrors ) {
        // Extract Uids from eventData.partialErrors
        const errorUids = partialErrors.map( error => error.uid );
        // Filter treeNodes based on errorUids and set selection to those nodes
        const errorNodes = treeNodes.filter( node => errorUids.includes( node.uid ) );
        treeDataProvider.setSelectionEnabled( true );
        treeDataProvider.selectionModel.setSelection( errorNodes );
    }

    if( !_.isEmpty( deleted ) ) {
        // remove children from all levels of deleted nodes
        const rowsToBeRemoved = _getRowsToBeRemoved( selectedObjectsArr, deleted, treeNodes );
        viewModelCollection.removeLoadedObjects( rowsToBeRemoved );
        // remove the deleted nodes from the children array of the parent
        _removeDeletedNodesFromParent( selectedObjectsArr, treeDataProvider );
        const finalNodes = viewModelCollection.getLoadedViewModelObjects();
        treeDataProvider.update( finalNodes );
        shouldGridVisible = finalNodes.length > 1;

        if( !partialErrors ) {
            //Set selection to top context if there are no partial errors
            let context = treeDataProvider.topTreeNode.children[ 0 ];
            treeDataProvider.setSelectionEnabled( true );
            treeDataProvider.selectionModel.setSelection( context );
        }
    }
    return shouldGridVisible;
};

