/** Update the searchState atomic object with the selected features from the internavigating Feature Selector Panel
 * activeFilterMap in search state is used to send filter panel selections to the Constraints Provider
 * Active filters are passed through searchFilterMap6 field of search input
 * Features selected from the grid should be displayed in the features list, prepare the selections data and return
 * @param { Object } searchState searchState atomic object
 * @param { Object } eventData eventData with Feature Selector Panel selection data
 * @returns { Object } Feature list selections data
 */
export let selectFeatureFacetsFromVariabilityPickerSubPanel = ( searchState, eventData ) => {
    // Filter only features and families from the selection
    const newSearchState = { ...searchState.getValue() };

    const selectedData = [ ...newSearchState.selectedVariability.vmoSelected, ...newSearchState.selectedVariability.userSelectionsPickAndChooseGrid ];
    const cachedFeatures = newSearchState.featuresFilterCategory.featureFacetValues;
    let featuresCategoryValues = [];
    let featureUids = [];
    selectedData.forEach( ( vmo ) => {
        if( _.isString( vmo ) || vmo.isFamily || vmo.isFeature ) {
            let featureFacetDisplayName = '';
            /**
             * selectedData can be either feature uid as string or feature VMO object
             */
            if( _.isString( vmo ) && featureUids.indexOf( vmo ) === -1 ) {
                for( let feature of cachedFeatures ) {
                    if( feature.propInternalValue === vmo ) {
                        vmo = { uid: feature.propInternalValue, propDisplayValue: feature.propDisplayValue };
                        featureFacetDisplayName = feature.propDisplayValue;
                        break;
                    }
                }
            } else if( _.isObject( vmo ) && !vmo.isFamily && _.intersection( pca0Constants.CFG_FAMILY_FEATURES_TYPES, vmo.modelType.typeHierarchyArray ).length > 0 ) {
                let familyVMO = cdm.getObject( vmo.parentUID );
                const [ featureParentName ] = familyVMO.props.object_string.dbValues;
                featureFacetDisplayName = vmo.displayName + ' (' + featureParentName + ')';
            } else if( _.isObject( vmo ) && _.intersection( pca0Constants.CFG_FAMILY_FEATURES_TYPES, vmo.modelType.typeHierarchyArray ).length > 0 ) {
                featureFacetDisplayName = vmo.displayName;
            }
            if( !_.isString( vmo ) && vmo ) {
                let categoryValue = _getStringTypeCategoryFilterValue( featureFacetDisplayName, vmo.uid );
                featuresCategoryValues.push( categoryValue );
                featureUids.push( vmo.uid );
            }
        }
    } );
    let currentSelectedFilterValues = _convertSoaOutputFilterFacetsToFilterValues( pca0Constants.FILTER_CONSTRAINTS.FEATURES_FILTER_CATEGORY_INTERNAL_NAME, featuresCategoryValues );
    newSearchState.featuresFilterCategory.filterValues = currentSelectedFilterValues;
    const activeFilterMap = _getActiveFilterMap( [ newSearchState.constraintTypeFilterCategory, newSearchState.featuresFilterCategory ] );
    newSearchState.activeFiltersInfo.activeFilterMap = activeFilterMap;
    newSearchState.enableApplyFilter = !areActiveAndAppliedFiltersSame( newSearchState.activeFiltersInfo, newSearchState.appliedFiltersInfo );
    const configuratorExplorerLocaleTextBundle = localeService.getLoadedText( 'ConfiguratorExplorerMessages' );
    const configuratorLocaleTextBundle = localeService.getLoadedText( 'ConfiguratorMessages' );
    newSearchState.featuresFilterChipData = _generateChipFromActiveFilters( newSearchState.activeFiltersInfo.activeFilterMap, pca0Constants.FILTER_CONSTRAINTS.FEATURES_FILTER_CATEGORY_INTERNAL_NAME,
        configuratorExplorerLocaleTextBundle.familiesAndFeatures, configuratorLocaleTextBundle.selected );
    searchState.update( newSearchState );
};

