/**
 * Update Object after revise action is performed
 * @param {Object} selectedObject - vmo of the selected object
 * @param {Object} treeDataProvider - tree Data Provider
 * @param {Object} response - response of the soa
 */
export let updateObjectAfterRevise = ( selectedObject, treeDataProvider, response ) => {
    // when the revise object is configured in
    if( response.objects.length > 0 ) {
        const viewModelCollection = treeDataProvider.getViewModelCollection();
        const viewModelObjects = treeDataProvider.getViewModelCollection().getLoadedViewModelObjects();

        let selectedObjIndx = viewModelCollection.findViewModelObjectById( selectedObject.uid );
        const selectedObjVmo = viewModelObjects[ selectedObjIndx ];

        // Create a new VMO for the revised object
        let newVMO = awTableTreeSvc.createViewModelTreeNode( response.objects[ 0 ].uid, response.objects[ 0 ].type, selectedObjVmo.displayName,
            selectedObjVmo.levelNdx, selectedObjVmo.childNdx, selectedObjVmo.iconURL, selectedObjVmo.svgString );

        // Update the required properties of the newVMO
        newVMO.nodeUid = newVMO.uid;
        if( selectedObjVmo.isLeaf ) {
            newVMO.isLeaf = true;
        }

        // Get parent vmo from viewModelCollection, this will be used for preparing alternateID for revised object.
        // parent vmo is also required to splice the parentChildren with revised object.
        const parentNodeUid = selectedObjVmo.parentUID;
        if( parentNodeUid ) {
            let parentNodeIndx = viewModelCollection.findViewModelObjectById( parentNodeUid );
            if( parentNodeIndx === -1 ) {
                parentNodeIndx = viewModelObjects.findIndex( vmo => vmo.uid === parentNodeUid );
            }
            let parentVMO = viewModelCollection.getViewModelObject( parentNodeIndx );
            newVMO.parentUID = parentNodeUid;
            newVMO.alternateID = pca0CommonUtils.prepareUniqueId( parentVMO.alternateID, newVMO.uid );

            // If the node being revised is expanded, then splice remove the expanded children from the viewModelObjects.
            // This is applicable only when we are revising the family and family is expanded.
            // When feature is revised we don't have children array in selectedObjVmo, which will not perform removal of children from selectedObjVmo.
            // In this case we will see a collapsed revised node and when we expand the revised node we will get the variability under it.
            if( !_.isUndefined( selectedObjVmo.children ) && selectedObjVmo.children.length > 0 ) {
                const childrenLength = selectedObjVmo.children.length;
                // Remove the expanded children from viewModelObjects of the node being revised.
                viewModelObjects.splice( ++selectedObjIndx, childrenLength );
                // Empty the children array for the node being revised.
                viewModelObjects[ --selectedObjIndx ].children = [];
            }

            // Similarly splice the updated object from parent and the viewModelObjects.
            const revisedObjIndxInParentVMO = parentVMO.children.findIndex( ( childTreeViewNode ) => childTreeViewNode.nodeUid === selectedObjVmo.nodeUid );
            // Update the parentVMO children list with the newVMO
            parentVMO.children.splice( revisedObjIndxInParentVMO, 1, newVMO );
        }

        // Update the viewModelObjects list with newVMO
        viewModelObjects.splice( selectedObjIndx, 1, newVMO );
        treeDataProvider.selectionModel.setSelection( newVMO );
        treeDataProvider.update( viewModelObjects );
    } else {
        // when the revise object is configured out- show the message
        const msg = pca0CommonUtils.getLocalizedValue( 'revisionConfiguredOut', explorerMessageFile );
        messagingService.showInfo( msg );
    }
};

