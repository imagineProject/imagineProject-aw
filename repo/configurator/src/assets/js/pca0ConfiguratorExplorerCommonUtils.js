/*
 * This function returns constraints to select from search result.
 * If all constraints are of type matrix rule, it returns the matrix rules and opens it in matrix view
 * If all constraints are not of type matrix rule, it returns all constraints and opens it in grid view
 * If there are constraints of both types, it doesnot return any constraints and opens overview tab
 * @param {Object} searchResults - search results object
 * @returns {Object} itemsToSelectAndOpen - Items to select and open in the configurator
 * @returns {String} tabId - Tab ID to open the selected items
 */
export let getItemsToSelect = ( searchResults ) => {
    let constraints = searchResults.objects;
    // Filter out the matrix rules from the constraints
    let matrixRules = constraints.filter( constraint => constraint.type === 'Cfg0MatrixRule' );

    if( matrixRules.length === 0 ) {
        // If matrix rule type constraints are not present, return all constraints and open in grid view
        return { itemsToSelectAndOpen: constraints, tabId: 'Pca0ConstraintsGridEditorWrapper' };
    } else if( constraints.length === matrixRules.length ) {
        // If all constraints are of type matrix rule, return the matrix rules and open in matrix view
        return { itemsToSelectAndOpen: constraints, tabId: 'Pca0ConstraintsSnOMatrixWrapper' };
    }
    // If there are constraints of both types, return empty array and open in overview tab
    return { itemsToSelectAndOpen: [], tabId: 'tc_xrt_Overview' };
};

