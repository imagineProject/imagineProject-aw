/**
 * Update column details with sorting and filtering flags
 * @param {Object} columns Columns to set filtering and sorting flag
 * @param {Object} columnsToDisableSort List of columns that do not support sorting
 * @param {Object} columnsToDisableFilter List of columns that do not support filtering
 * @returns {Object} updated columns
 */
export let disableColumnSortingAndFiltering = function( columns, columnsToDisableSort, columnsToDisableFilter ) {
    let newColumns = _.cloneDeep( columns );
    _.forEach( newColumns, column => {
        let propertyName = column.propertyName;

        // Attach necessary renderers
        exports.attachRequiredRenderers( column );

        if( columnsToDisableSort ) {
            column.enableSorting = !columnsToDisableSort.includes( propertyName );
        }
        if( columnsToDisableFilter ) {
            column.isFilteringEnabled = !columnsToDisableFilter.includes( propertyName );
        }
    } );
    return newColumns;
};

/**
 * Attach necessary renderers to input column
 * @param {Object} column input column which renderers need to be attached to
 */
export let attachRequiredRenderers = function( column ) {
    // Required renderer is needed (for now until framework supports it):
    // for NAME column on group, family and feature
    // in case of the feature: only on name column for types bool and string - default
    // and on ID vmo for feature of type date, float, int
    column.cellRenderers = [];
    if( column.propertyName === 'object_name' || column.propertyName === 'cfg0ObjectId' ) {
        // Attach required/autogenerated renderer
        column.cellRenderers = [];
        column.cellRenderers.push( _getCustomRenderers() );
    }
    column.cellRenderers.push( _getFailedToSaveInlineRowRenderer() );
    if( column.propertyName === 'object_string' ) {
        // Attach dirty renderer
        column.cellRenderers.push( _getDirtyRenderer() );
    }
};

/**
 * Build SOA Search input for querying Variants or Constraints
 * @param {string} uidOfObject this is the uidOfLastRule or uid of reviseObject
 * @param {string} tag this tag will differentiate the function call
 * @param {string} searchState search state atomic object
 * @param {Array} newlyCreatedObjUids newly created object UIDs
 * @param {Number} startIndex start index of the search
 * @param {Object} variantRuleData loaded SVR atomic data
 * @returns {Object} ConfigPerspectiveUID
 */
export let getInputAndReviseCriteria = ( uidOfObject, tag, searchState, newlyCreatedObjUids, startIndex, variantRuleData ) => {
    let { configPerspective } = pca0CommonUtils.getConfigPerspectiveAndContextUid( variantRuleData );


    let criteria = {
        configPerspective: configPerspective.uid,
        inputObjectUids: _getInputObjectsUids(),

        //Variants
        // "useImanRelation" flag will be used in server to decide whether to use saved search query or use GRM api to get variant rules.
        // This flag is temporary to fix LCS-988601. It will be removed once we restructure saved variants search input.
        // We are using this flag here only, as we are not mentioning anywhere in variants tab the way we are fetching variant rules.
        // And If we use saved query to get variants tab it will give results only if the variant names are localized or in english locale
        // But we want to show it in all locales without localization.
        useImanRelation: 'true'
    };

    // setting allRevisions to true based one 'compareRevisions'
    // This flag ignores the filtering of revisions and shows all the revisions of the object which is being sent.
    if ( awStateService.instance.params.compareRevisions ) {
        criteria.allRevisions = 'true';
    }

    // Add featureSearchType and searchOperationType in search criteria only when filtering the constraints by feature
    // featureSearchType - decides where to search feature(s) in constraint ( search_only_in_subject / search_only_in_condition / search_either_in_subject_or_condition)
    // searchOperationType - When more than one features are selected, operation between these features (AND/OR)
    if( !_.isUndefined( searchState ) ) {
        let newSearchState = searchState.getValue ? { ...searchState.getValue() } : searchState;
        if( !_.isUndefined( newSearchState.activeFiltersInfo ) ) {
            let activeFeatureCategoryFilters = newSearchState.activeFiltersInfo.activeFilterMap[ pca0Constants.FILTER_CONSTRAINTS.FEATURES_FILTER_CATEGORY_INTERNAL_NAME ];
            if( !_.isUndefined( activeFeatureCategoryFilters ) && !_.isEmpty( activeFeatureCategoryFilters ) ) {
                criteria.featureSearchType = newSearchState.activeFiltersInfo.featureSearchType;
                criteria.searchOperationType = newSearchState.activeFiltersInfo.searchOperationType;
                criteria.matchType = criteria.searchOperationType === pca0Constants.CFG_FILTER_OPERATION_TYPE.ALL ? 'allMatch' : 'anyMatch';
            }
            if( newSearchState.activeFiltersInfo[ pca0Constants.FILTER_CONSTRAINTS.UNREFERENCED_TYPE_FILTER_CATEGORY_INTERNAL_NAME] ) {
                criteria.unReferencedRulesOnly = 'true';
            }
        }
    }

    if( !_.isUndefined( uidOfObject ) && !_.isEmpty( uidOfObject ) ) {
        if( tag === 'revise' || tag === 'add' ) {
            const jsn = JSON.stringify( [ uidOfObject ] );
            criteria.selectedObjects = jsn;
        } else if ( startIndex > 0 ) {
            // Only set uidOfLastRule if startIndex is greater than 0
            criteria.uidOfLastRule = uidOfObject;
        }
    }
    // Newly created object uids are passed only when we are scrolling the table.
    // if we pass it after creating the first object, it will filter out the object we just created.
    if( !_.isUndefined( newlyCreatedObjUids ) && !_.isEmpty( newlyCreatedObjUids ) && startIndex >= 50 ) {
        criteria.newlyCreatedObjUids = JSON.stringify( newlyCreatedObjUids );
    }
    return criteria;
};

