/**
 * Helper API to compare the active filters with the applied filters
 * If the applied filters are same as active filters disable the Filter button
 * @param {String} activeFiltersInfo active filters map
 * @param {String} appliedFiltersInfo applied filters map
 * @returns {boolean} true if the applied filters and active filters are same
 */
export const areActiveAndAppliedFiltersSame = ( activeFiltersInfo, appliedFiltersInfo ) => {
    const activeFilterMap = activeFiltersInfo.activeFilterMap;
    const appliedFilterMap = appliedFiltersInfo.appliedFilterMap;
    const activeFilterCategoryNames = Object.keys( activeFilterMap );

    if( activeFiltersInfo[ pca0Constants.FILTER_CONSTRAINTS.UNREFERENCED_TYPE_FILTER_CATEGORY_INTERNAL_NAME ] !==
        appliedFiltersInfo[ pca0Constants.FILTER_CONSTRAINTS.UNREFERENCED_TYPE_FILTER_CATEGORY_INTERNAL_NAME ] ) {
        return false;
    }

    for( let filterCategoryName of activeFilterCategoryNames ) {
        const activeFilterFacetsForCategory = activeFilterMap[ filterCategoryName ].map( item => item.stringValue ).sort();
        const appliedFilterFacetsForCategory = appliedFilterMap[ filterCategoryName ].map( item => item.stringValue ).sort();

        if( activeFilterFacetsForCategory.length !== appliedFilterFacetsForCategory.length ) {
            return false;
        }

        for( let i = 0; i < activeFilterFacetsForCategory.length; i++ ) {
            if( activeFilterFacetsForCategory[ i ] !== appliedFilterFacetsForCategory[ i ] ) {
                return false;
            }
        }
    }
    return true;
};

